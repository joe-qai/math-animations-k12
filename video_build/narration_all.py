def duration_of(path: Path) -> float:
    out = subprocess.run(
        [
            "ffprobe", "-v", "error",
            "-show_entries", "format=duration",
            "-of", "default=noprint_wrappers=1:nokey=1",
            str(path),
        ],
        capture_output=True,
        text=True,
    )
    return float(out.stdout.strip())


async def build_one(lesson_id: str, segments: list[str]) -> None:
    out_dir = AUDIO_ROOT / lesson_id
    out_dir.mkdir(parents=True, exist_ok=True)
    timings = []
    for i, text in enumerate(segments):
        path = out_dir / f"seg_{i:02d}.mp3"
        communicate = edge_tts.Communicate(text, VOICE, rate=RATE)
        await communicate.save(str(path))
        d = duration_of(path)
        timings.append(
            {
                "index": i,
                "file": str(path.relative_to(ROOT)).replace("\\", "/"),
                "text": text,
                "duration": round(d, 3),
            }
        )
        print(f"[OK] {lesson_id} seg_{i:02d} {d:6.2f}s")

    (out_dir / "timings.json").write_text(
        json.dumps(timings, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    total = sum(t["duration"] for t in timings)
    print(f"[DONE] {lesson_id}: {len(segments)} segments, {total:.1f}s")


async def main() -> None:
    only = sys.argv[1] if len(sys.argv) > 1 else None
    targets = {k: v for k, v in LESSONS.items() if only is None or k == only}
    if not targets:
        print(f"[ERR] unknown lesson: {only}")
        return
    for lesson_id, segments in targets.items():
        await build_one(lesson_id, segments)


if __name__ == "__main__":
    asyncio.run(main())